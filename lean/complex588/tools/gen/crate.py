"""crate.py: rate, instance and final modules of the bridged word B_2 with a kernel-checked CARRIER
certificate, and the comparator packages.  Text generators: foldlib, foldgen, b2inst (beside this file).

usage: crate.py <Inst> <CertName> [--out <dir>]          (default <dir>: tools/gen/out, never the source tree)
   e.g. crate.py B2Ke16 Cr2h16
   reads   <dir>/Work/CarrierCheck/<CertName>Cert.lean  (written by ccgen.py; statement of `ranks_cost`: the
           kernel-counted ranks of one invocation) and the two text templates tools/gen/templates/*.lean.txt
   writes  <dir>/Work/CarrierCheck/Rate<Inst>.lean, Rate<Inst>x.lean      rate lemmas (whole-block, per-rank, sharpness)
           <dir>/Work/CarrierCheck/Inst<Inst>.lean                         unit price = price of the block list; conditional theorems
           <dir>/Work/CarrierCheck/<Inst>.lean                             network certificate + the WHT theorems
           <dir>/Work/CarrierCheck/Challenge<Inst>x.lean, Solution<Inst>x.lean, <dir>/comparator/<Inst>x.json
                                                                           comparator package, whole-block, ten decimals
           the same with the suffix xR (per-rank, ten decimals) and with no suffix (whole-block, eight decimals)
           <dir>/tools/gen/logs/rate-<Inst>.json, rate-<Inst>x.json        the numbers chosen (information only)

Unit of the bridged word B_2: W = 4 v + R live roles, m = 5 h,
   block list = 5 x (blocks of one invocation, ALL roles) + 2 v x {h-1, 2h-2, 2h+2, 4}   (idle climbs of the twins).

The generated Lean files name the generators by their paths in the tree they were made in
(`checks/wht12/carrier-check/py/crate.py`, `checks/wht9/bridge-rate/py`); that text is kept so that the output
is byte-identical.
"""
import sys, re, json, os
LIB = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, LIB)
import foldlib as fl
import foldgen as fg
import b2inst as bi

# OUT = where the files are written (changed by --out); TPL = the two text templates
OUT = LIB + '/out/'
TPL = LIB + '/templates/'
NS = 'OAI.PowerSaving.BlockAccounting'


def cert_data(cname):
    src = open(OUT + 'Work/CarrierCheck/%sCert.lean' % cname).read()
    i = src.index('theorem ranks_cost')
    stmt = src[i:src.index(':= by', i)]
    stmt = stmt[stmt.index('cert.invRanks =') + len('cert.invRanks ='):]
    inv = {int(r): int(n) for n, r in re.findall(r'(\d+) \* φ (\d+)', stmt)}
    g = lambda k: int(re.search(r'theorem cert_%s : .* = (\d+) := rfl' % k, src).group(1))
    return inv, g('h'), g('v'), g('R'), g('nc')


def unit(inv, h, v, R):
    H = {}

    def add(r, n):
        if n:
            H[r] = H.get(r, 0) + n
    for r, n in inv.items():
        add(r, 5 * n)
    for cv, rk in fl.BANK['B2']:
        add(rk(h), cv * v)
    m, W = 5 * h, 4 * v + R
    D = W * m - sum(r * n for r, n in H.items())
    assert D == 4 * v - 5 * ((h - 1) ** 2 + h), D
    return dict(kind='B2', h=h, m=m, W=W, D=D, v=v, R=R, H=H, inv=inv)


def rate_module(name, u, B, s, cname):
    A, Af, Ar, Arf = fl.best_units(u, B, s)
    while fl.plan_block(u, A, B, s) is None:
        A -= 1
    while fl.plan_rank(u, Ar, B, s) is None:
        Ar -= 1
    while fl.plan_sharp(u, Af, B) is None:
        Af += 1
    k = 0
    while fg.rank_sharp_text(name, u, Arf, B) is None and k < 20:
        Arf += 1
        k += 1
    m, W, D = u['m'], u['W'], u['D']
    doc = ('Block list `(rank, count)` of ONE unit of the bridged five-stage word B_2 with the CARRIER helper circuit '
           '`%s` (h = %d, m = %d): five invocations (ALL blocks of one invocation: x roles, y roles, helper slots, scratch '
           'copies; the kernel-counted ranks of `Carrier%s.inv_cost`), and for each of the v = %d classes the idle climbs '
           'of its two twins (2 blocks each of rank h-1, 2h-2, 2h+2, 4); R = %d helper slots shared by the five stages.'
           % (cname, u['h'], m, cname, u['v'], u['R']))
    lst = fg.list_text(name, u, doc)
    blk, P = fg.block_text(name, u, A, B, s)
    shp, PS = fg.sharp_text(name, u, Af, B)
    rk, PR = fg.rank_text(name, u, Ar, B, s)
    rks = fg.rank_sharp_text(name, u, Arf, B)
    assert rks is not None
    head = f'''import Work.BlockAccounting.Moment
import Work.BlockAccounting.Sharp
import Work.FoldRate.RankTools

/-!
# (key: carrier-check) Rate lemmas for one unit of the bridged word B_2 with the carrier certificate `{cname}`

GENERATED by checks/wht12/carrier-check/py/crate.py with the text generators of
checks/wht9/bridge-rate/py (used read-only).  No `sorry`.  Arithmetic only.

One unit: `W = {W}` live roles, label dimension `m = {m}`, deficit `D = {D}`.

* `blocks{name}`            the block list (rank, count) of ONE unit;
* `fold_{name}`             whole-block fact at `1 - {A}/10^{B}`, fill parameter `s = {s}` (slack {P["slack_rel"]:.2e});
* `fold_{name}_sharp`       `W ≤ moment` at `1 - {Af}/10^{B}`: fails for every table (excess {PS["slack_rel"]:.2e});
* `foldRank_{name}`         per-rank fact at `1 - {Ar}/10^{B}`, `s = {s}` (slack {PR["slack_rel"]:.2e});
* `foldRank_{name}_sharp`   per-rank: fails for every table at `1 - {Arf}/10^{B}`.

That a Lean word has `G` times this list as its block histogram is NOT proved here (see `Work.CarrierCheck.{name.rstrip("x")}`).
-/

set_option maxRecDepth 4000

namespace {NS}
open Finset

'''
    body = lst + '\n' + blk + '\n' + shp + '\n' + rk + '\n' + rks
    foot = f'\nend {NS}\n\n' + '\n'.join('#print axioms %s.%s_%s' % (NS, a, b) for a, b in
                                        [('fold', name), ('fold', name + '_sharp'), ('foldRank', name),
                                         ('foldRank', name + '_sharp')]) + '\n'
    open(OUT + 'Work/CarrierCheck/Rate%s.lean' % name, 'w').write(head + body + foot)
    info = dict(name=name, m=m, W=W, D=D, H=u['H'], A=A, A_fails=Af, A_rank=Ar, A_rank_fails=Arf, B=B, s=s,
                slack=P['slack_rel'], excess=PS['slack_rel'], rank_slack=PR['slack_rel'], rank_sharp=True,
                kind='B2', h=u['h'], R=u['R'], v=u['v'], inv=u['inv'], circuit='carrier:' + cname)
    json.dump(info, open(OUT + 'tools/gen/logs/rate-%s.json' % name, 'w'), indent=1)
    print('Rate%s: block %d/10^%d (fails %d), rank %d (fails %d), s=%d, slack %.2e, excess %.2e, rank slack %.2e'
          % (name, A, B, Af, Ar, Arf, s, P['slack_rel'], PS['slack_rel'], PR['slack_rel']))
    return info


