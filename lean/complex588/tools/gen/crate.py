def pack(name, A, B, term, pname, rank=False):
    """comparator package: the template templates/ChallengeB2L16x.lean.txt (an earlier comparator package,
    module Work.BridgeRate.ChallengeB2L16x, not in this repository) with theorem name and exponent changed"""
    src = open(TPL + 'ChallengeB2L16x.lean.txt').read()
    thm = ('wht_main_rank_' if rank else 'wht_main_block_') + name
    assert src.count('wht_main_block_B2L16x') == 2 and src.count('4059928/(10:ℝ)^10') == 2 and src.count('4059928/10^10') == 2
    new = (src.replace('wht_main_block_B2L16x', thm).replace('4059928/(10:ℝ)^10', '%d/(10:ℝ)^%d' % (A, B))
           .replace('4059928/10^10', '%d/10^%d' % (A, B))
           .replace('Work.BridgeRate.ChallengeB2L16x', 'Work.CarrierCheck.Challenge' + pname)
           .replace('Work.BridgeRate.SolutionB2L16x', 'Work.CarrierCheck.Solution' + pname))
    a, b = src.split('\n'), new.split('\n')
    assert len(a) == len(b)
    i1 = a.index('-/')
    changed = [k for k in range(len(a)) if a[k] != b[k]]
    code = [k for k in changed if k > i1]
    assert len(code) == 3, code                      # doc line of the theorem, theorem name, statement
    open(OUT + 'Work/CarrierCheck/Challenge%s.lean' % pname, 'w').write(new)
    sol = open(TPL + 'SolutionB2L16x.lean.txt').read()
    assert sol.count('wht_main_B2L16x') == 2
    sol = (sol.replace('wht_main_block_B2L16x', thm).replace('wht_main_B2L16x', term)
           .replace('Work.BridgeRate.B2L16x', 'Work.CarrierCheck.' + name.rstrip('x'))
           .replace('Work.BridgeRate.SolutionB2L16x', 'Work.CarrierCheck.Solution' + pname)
           .replace('4059928/(10:ℝ)^10', '%d/(10:ℝ)^%d' % (A, B)).replace('4059928/10^10', '%d/10^%d' % (A, B)))
    open(OUT + 'Work/CarrierCheck/Solution%s.lean' % pname, 'w').write(sol)
    cfg = {"challenge_module": 'Work.CarrierCheck.Challenge' + pname,
           "solution_module": 'Work.CarrierCheck.Solution' + pname,
           "theorem_names": ['OAI.PowerSaving.WHT.' + thm], "definition_names": [],
           "permitted_axioms": ["propext", "Quot.sound", "Classical.choice"], "enable_nanoda": False}
    json.dump(cfg, open(OUT + 'comparator/%s.json' % pname, 'w'), indent=2)
    print('packed', pname, thm, '1 - %d/10^%d' % (A, B), 'challenge lines changed (0-based):', changed)


if __name__ == '__main__':
    if '--out' in sys.argv:
        i = sys.argv.index('--out')
        OUT = os.path.abspath(sys.argv[i + 1]) + '/'
        del sys.argv[i:i + 2]
    for d in ('Work/CarrierCheck', 'comparator', 'tools/gen/logs'):
        os.makedirs(OUT + d, exist_ok=True)
    name, cname = sys.argv[1], sys.argv[2]
    inv, h, v, R, nc = cert_data(cname)
    u = unit(inv, h, v, R)
    print('unit %s: W=%d m=%d D=%d tally=%d blocks=%s' % (name, u['W'], u['m'], u['D'], u['W'] * u['m'] - u['D'],
                                                         sorted(u['H'].items())))
    d = rate_module(name, u, 8, 13, cname)
    dx = rate_module(name + 'x', u, 10, 40, cname)
    inst_module(name, cname, d, dx)
    final_module(name, cname, d, dx)
    pack(name + 'x', dx['A'], dx['B'], 'wht_main_%sx' % name, name + 'x')
    pack(name + 'x', dx['A_rank'], dx['B'], 'wht_main_perRank_%sx' % name, name + 'xR', rank=True)
    pack(name, d['A'], d['B'], 'wht_main_%s' % name, name)
