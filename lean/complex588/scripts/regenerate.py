#!/usr/bin/env python3
"""Regenerate all 63 new Lean modules and compare their bytes with this package."""
from pathlib import Path
import json
import shutil
import subprocess
import sys
import tempfile

ROOT=Path(__file__).resolve().parents[1]
TRACK=ROOT.parents[1]/"research/complex-transfer-588-596"


def main():
    with tempfile.TemporaryDirectory(prefix="complex588-regen-") as tmp:
        work=Path(tmp)
        certificate=work/"pr588-atm3-source-copies-no-cleanup.gcert.json.gz"
        shutil.copy2(ROOT/"artifacts/candidate.gcert.json.gz",certificate)
        shutil.copy2(ROOT/"artifacts/price.json",work/"price.json")
        shutil.copy2(ROOT/"artifacts/schedule.json.gz",work/"price.schedule.json.gz")
        out=work/"generated"
        commands=[
            ["generate_local_lean.py",str(certificate),"--toolkit",str(ROOT/"tools/gx"),"--out",str(out)],
            ["generate_global_lean.py",str(work/"price.json"),"--toolkit",str(ROOT/"tools/gen"),"--record",str(ROOT/"third-party/record-templates"),"--out",str(out)],
            ["generate_checks.py","--out",str(out),"--original-challenge",str(ROOT/"third-party/openai-math/lean/ComparatorChallenges/UniformFourier.lean"),"--comparator",str(ROOT/"tools/Compare.lean")]]
        for cmd in commands:
            subprocess.run([sys.executable,str(TRACK/"experiments"/cmd[0]),*cmd[1:]],check=True)
        files=sorted((out/"Work").rglob("*.lean"))
        assert len(files)==63,len(files)
        for p in files:
            rel=p.relative_to(out)
            assert p.read_bytes()==(ROOT/rel).read_bytes(),str(rel)
        print(f"PASS: {len(files)} new Lean modules regenerated byte for byte")


if __name__=="__main__":main()
